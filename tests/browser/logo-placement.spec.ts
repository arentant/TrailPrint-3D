test('SVG logo import, exact text / logo positions, dragging, preview and STL stay in sync', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await page.waitForLoadState('networkidle');
  await page.getByPlaceholder('Paste your API key').fill('browser-test-key');
  await page.getByRole('button', { name: 'Standard', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Base thickness', exact: true }).fill('3');
  await page.getByRole('switch', { name: 'Text on model', exact: true }).click();
  await page.getByRole('textbox', { name: 'Model text title', exact: true }).fill('RIDGE');
  await page.getByRole('combobox', { name: 'Model text placement', exact: true }).selectOption('both');
  await page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true }).fill('4');
  await page.getByRole('spinbutton', { name: 'Text vertical offset', exact: true }).fill('-8');
  await page.getByRole('spinbutton', { name: 'Text rotation', exact: true }).fill('10');
  await page.getByRole('button', { name: 'Underside layout', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true }).fill('8');
  await page.getByRole('spinbutton', { name: 'Text vertical offset', exact: true }).fill('14');
  await page.getByRole('spinbutton', { name: 'Text rotation', exact: true }).fill('20');
  await page.getByRole('switch', { name: 'Logo on model', exact: true }).click();
  await page.getByLabel('Logo file', { exact: true }).setInputFiles(resolve('fixtures/model-logo.svg'));
  await expect(page.getByRole('img', { name: 'Imported logo: model-logo.svg', exact: true })).toBeVisible();
  await page.getByRole('spinbutton', { name: 'Logo width', exact: true }).fill('16');
  await page.getByRole('group', { name: 'Feature to position', exact: true }).getByRole('button', { name: 'Logo', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true }).fill('-15');
  await page.getByRole('spinbutton', { name: 'Logo vertical offset', exact: true }).fill('-10');
  await page.getByRole('spinbutton', { name: 'Logo rotation', exact: true }).fill('30');
  const move = page.getByRole('button', { name: 'Move logo', exact: true });
  await move.scrollIntoViewIfNeeded();
  const box = (await move.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 16, box.y + box.height / 2 - 8, { steps: 6 });
  await page.mouse.up();
  expect(Number(await page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true }).inputValue())).toBeGreaterThan(-15);
  expect(Number(await page.getByRole('spinbutton', { name: 'Logo vertical offset', exact: true }).inputValue())).toBeGreaterThan(-10);
  await page.getByRole('combobox', { name: 'Logo placement', exact: true }).selectOption('both');
  await page.getByRole('button', { name: 'Front layout', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true }).fill('-12');
  await page.getByRole('spinbutton', { name: 'Logo vertical offset', exact: true }).fill('-5');
  await page.getByRole('spinbutton', { name: 'Logo rotation', exact: true }).fill('15');
  await expect(page.locator('.model-features__error')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/logo-placement-editor.png', fullPage: true });
  await page.evaluate(() => {
    const generate = window.trailPrint.generateTerrain;
    window.trailPrint.generateTerrain = async request => {
      const response = await generate(request);
      Object.assign(window, { logoPlacementPreview: { config: request.config, response } }); return response;
    };
  });
  await page.getByRole('button', { name: 'Preview & export STL', exact: true }).click();
  const dialog = page.getByRole('dialog'), download = dialog.getByRole('button', { name: 'Download', exact: true });
  await expect(download).toBeEnabled({ timeout: 60_000 });
  const generated = await page.evaluate(() => (window as unknown as { logoPlacementPreview: Preview }).logoPlacementPreview);
  expect(generated.config.terrain.logo.asset!.contours).toHaveLength(2);
  expect(generated.config.terrain.text.frontPosition).toEqual({ xMm: 4, yMm: -8, rotationDeg: 10 });
  expect(generated.config.terrain.text.undersidePosition).toEqual({ xMm: 8, yMm: 14, rotationDeg: 20 });
  expect(generated.config.terrain.logo.frontPosition).toEqual({ xMm: -12, yMm: -5, rotationDeg: 15 });
  expect(generated.config.terrain.logo.undersidePosition.rotationDeg).toBe(30);
  expect(analyzeMesh(generated.response.mesh).boundaryEdges).toBe(0);
  await page.getByRole('button', { name: 'View underside', exact: true }).click();
  await page.screenshot({ path: 'test-results/logo-engraving-underside.png', fullPage: true });
  const event = page.waitForEvent('download'); await download.click();
  const files = unzipSync(await readFile((await (await event).path())!));
  const stl = files[Object.keys(files).find(name => name.endsWith('_Terrain_Main.stl'))!]!;
  expect(new DataView(stl.buffer, stl.byteOffset).getUint32(80, true)).toBe(generated.response.mesh.indices.length / 3);
  expect(errors).toEqual([]);
});

test('PNG artwork, validation, removal and imported-logo presets work locally', async ({ page }) => {
  await page.goto('/'); await page.waitForLoadState('networkidle');
  await page.getByRole('switch', { name: 'Logo on model', exact: true }).click();
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 64;
    const context = canvas.getContext('2d')!;
    context.fillStyle = 'white'; context.fillRect(0, 0, 64, 64);
    context.fillStyle = 'black'; context.fillRect(8, 8, 48, 48);
    context.fillStyle = 'white'; context.fillRect(24, 24, 16, 16);
    return canvas.toDataURL('image/png').split(',')[1]!;
  });
  await page.getByLabel('Logo file', { exact: true }).setInputFiles({ name: 'ring.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await expect(page.getByRole('img', { name: 'Imported logo: ring.png', exact: true })).toBeVisible();
  await page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true }).fill('10');
  await page.getByRole('spinbutton', { name: 'Logo rotation', exact: true }).fill('25');
  await page.getByRole('button', { name: 'Save preset', exact: true }).click();
  await page.getByRole('textbox', { name: 'Preset name', exact: true }).fill('Logo position');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const preset = await page.evaluate(() => JSON.parse(localStorage.getItem('trailprint.configSchemes')!)[0]);
  expect(preset.payload.terrain.logo.asset.contours).toHaveLength(2);
  await page.reload();
  await page.getByTitle('Apply a saved preset', { exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: /Logo position/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Apply', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Imported logo: ring.png', exact: true })).toBeVisible();
  await expect(page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true })).toHaveValue('10');
  await expect(page.getByRole('spinbutton', { name: 'Logo rotation', exact: true })).toHaveValue('25');
  await page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true }).fill('100');
  await expect(page.locator('.model-features__error')).toContainText('Logo extends outside');
  await page.getByRole('button', { name: 'Reset logo position', exact: true }).click();
  await expect(page.locator('.model-features__error')).toHaveCount(0);
  await page.getByLabel('Logo file', { exact: true }).setInputFiles({ name: 'unsafe.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>') });
  await expect(page.locator('.logo-controls__error')).toContainText('outlined shapes');
  await expect(page.getByRole('img', { name: 'Imported logo: ring.png', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Remove logo', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Imported logo: ring.png', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Import SVG or PNG', exact: true })).toBeVisible();
  expect(await page.locator('.sidebar').evaluate(el => el.scrollWidth - el.clientWidth)).toBe(0);
});

test('quick placement presets arrange text and logos independently and preserve manual editing', async ({ page }) => {
  await page.goto('/'); await page.waitForLoadState('networkidle');
  await page.getByRole('switch', { name: 'Text on model', exact: true }).click();
  await page.getByRole('textbox', { name: 'Model text title', exact: true }).fill('RIDGE');
  await page.getByRole('combobox', { name: 'Model text placement', exact: true }).selectOption('both');
  await page.getByRole('spinbutton', { name: 'Text rotation', exact: true }).fill('20');
  const quick = page.getByRole('group', { name: 'Quick placement', exact: true });
  await expect(quick.getByRole('button')).toHaveCount(9);
  await quick.getByRole('button', { name: 'Center', exact: true }).click();
  await expect(quick.getByRole('button', { name: 'Center', exact: true })).toHaveAttribute('aria-pressed', 'true');
  const front = { x: await page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true }).inputValue(),
    y: await page.getByRole('spinbutton', { name: 'Text vertical offset', exact: true }).inputValue() };
  await page.getByRole('button', { name: 'Underside layout', exact: true }).click();
  for (const [label, xSign, ySign] of [['Top left', -1, 1], ['Top', 0, 1], ['Top right', 1, 1], ['Left', -1, 0],
    ['Right', 1, 0], ['Bottom left', -1, -1], ['Bottom', 0, -1], ['Bottom right', 1, -1]] as const) {
    await quick.getByRole('button', { name: label, exact: true }).click();
    const x = Number(await page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true }).inputValue());
    const y = Number(await page.getByRole('spinbutton', { name: 'Text vertical offset', exact: true }).inputValue());
    expect(Math.sign(x)).toBe(xSign); expect(Math.sign(y)).toBe(ySign);
    await expect(page.locator('.model-features__error')).toHaveCount(0);
    await expect(page.getByRole('spinbutton', { name: 'Text rotation', exact: true })).toHaveValue('0');
  }
  await page.getByRole('spinbutton', { name: 'Text rotation', exact: true }).fill('25');
  await quick.getByRole('button', { name: 'Center', exact: true }).click();
  await expect(quick.getByRole('button', { name: 'Center', exact: true })).toHaveAttribute('aria-pressed', 'true');
  // Rotated glyph bounds can need a small offset to center the visible lettering.
  const centeredY = Number(await page.getByRole('spinbutton', { name: 'Text vertical offset', exact: true }).inputValue());
  await expect(page.getByRole('spinbutton', { name: 'Text rotation', exact: true })).toHaveValue('25');
  await page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true }).fill('2');
  await expect(quick.getByRole('button', { name: 'Center', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Front layout', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true })).toHaveValue(front.x);
  await expect(page.getByRole('spinbutton', { name: 'Text vertical offset', exact: true })).toHaveValue(front.y);
  await expect(page.getByRole('spinbutton', { name: 'Text rotation', exact: true })).toHaveValue('20');
  await page.getByRole('switch', { name: 'Logo on model', exact: true }).click();
  await page.getByLabel('Logo file', { exact: true }).setInputFiles(resolve('fixtures/model-logo.svg'));
  await expect(page.getByRole('img', { name: 'Imported logo: model-logo.svg', exact: true })).toBeVisible();
  await page.getByRole('group', { name: 'Feature to position', exact: true }).getByRole('button', { name: 'Logo', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Logo rotation', exact: true }).fill('15');
  await quick.getByRole('button', { name: 'Bottom right', exact: true }).click();
  await expect(quick.getByRole('button', { name: 'Bottom right', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(Number(await page.getByRole('spinbutton', { name: 'Logo horizontal offset', exact: true }).inputValue())).toBeGreaterThan(0);
  expect(Number(await page.getByRole('spinbutton', { name: 'Logo vertical offset', exact: true }).inputValue())).toBeLessThan(0);
  await expect(page.getByRole('spinbutton', { name: 'Logo rotation', exact: true })).toHaveValue('15');
  await expect(page.locator('.model-features__error')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/quick-placement-presets.png', fullPage: true });
  await page.getByRole('group', { name: 'Feature to position', exact: true }).getByRole('button', { name: 'Text', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'Text horizontal offset', exact: true })).toHaveValue('2');
  await page.getByRole('button', { name: 'Save preset', exact: true }).click();
  await page.getByRole('textbox', { name: 'Preset name', exact: true }).fill('Quick positions');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const payload = await page.evaluate(() => JSON.parse(localStorage.getItem('trailprint.configSchemes')!)[0].payload);
  expect(payload.terrain.text.undersidePosition).toEqual({ xMm: 2, yMm: centeredY, rotationDeg: 25 });
  expect(payload.terrain.logo.undersidePosition.xMm).toBeGreaterThan(0);
});
